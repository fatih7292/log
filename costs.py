"""
LOG ANALYTICS — модуль анализа логистических ЗАТРАТ.

Соответствует Неделям 5–6 плана:
- Неделя 5: агрегация и группировка затрат по направлениям / регионам / перевозчикам
- Неделя 6: расчёт KPI — грузооборот (т·км), удельная стоимость (тенге/т·км),
            среднерыночный тариф и отклонение от него по каждому рейсу

Работает с реальным файлом: data/logistics_data.csv
Колонки: ID_рейса, Дата, Регион_отправления, Регион_назначения, Тип_груза,
         Вид_транспорта, Перевозчик, Вес_тонн, Расстояние_км, Стоимость_тенге
"""

import pandas as pd
from pathlib import Path

DATA_PATH = "data/logistics_data.csv"


# ------------------------------------------------------------------
# Загрузка
# ------------------------------------------------------------------

def load_data(path: str = DATA_PATH) -> pd.DataFrame:
    """Загружает CSV с логами перевозок (учитывает BOM в начале файла)."""
    path = Path(path)
    if not path.exists():
        raise FileNotFoundError(f"Файл не найден: {path}")

    df = pd.read_csv(path, encoding="utf-8-sig", parse_dates=["Дата"])
    return df


# ------------------------------------------------------------------
# KPI (Неделя 6)
# ------------------------------------------------------------------

def add_kpi_columns(df: pd.DataFrame) -> pd.DataFrame:
    """
    Добавляет ключевые логистические метрики к каждому рейсу:
      - Грузооборот_ткм      = Вес_тонн * Расстояние_км
      - Стоимость_за_ткм     = Стоимость_тенге / Грузооборот_ткм
      - Отклонение_от_среднего_% = во сколько % тариф рейса выше/ниже среднерыночного
    """
    df = df.copy()

    df["Грузооборот_ткм"] = df["Вес_тонн"] * df["Расстояние_км"]
    df["Стоимость_за_ткм"] = df["Стоимость_тенге"] / df["Грузооборот_ткм"]

    avg_rate = df["Стоимость_за_ткм"].mean()
    df["Отклонение_от_среднего_%"] = (df["Стоимость_за_ткм"] / avg_rate - 1) * 100

    return df


# ------------------------------------------------------------------
# Группировка / агрегация затрат (Неделя 5)
# ------------------------------------------------------------------

def costs_by_carrier(df: pd.DataFrame) -> pd.DataFrame:
    """Сводная таблица затрат по перевозчикам."""
    result = df.groupby("Перевозчик").agg(
        Число_рейсов=("ID_рейса", "count"),
        Общая_стоимость_тенге=("Стоимость_тенге", "sum"),
        Средняя_стоимость_за_ткм=("Стоимость_за_ткм", "mean"),
        Суммарный_грузооборот_ткм=("Грузооборот_ткм", "sum"),
    ).sort_values("Общая_стоимость_тенге", ascending=False)
    return result.round(2)


def costs_by_region(df: pd.DataFrame) -> pd.DataFrame:
    """Сводная таблица затрат по направлениям (регион отправления → назначения)."""
    result = df.groupby(["Регион_отправления", "Регион_назначения"]).agg(
        Число_рейсов=("ID_рейса", "count"),
        Общая_стоимость_тенге=("Стоимость_тенге", "sum"),
        Средняя_стоимость_за_ткм=("Стоимость_за_ткм", "mean"),
    ).sort_values("Общая_стоимость_тенге", ascending=False)
    return result.round(2)


def costs_by_transport_type(df: pd.DataFrame) -> pd.DataFrame:
    """Сводная таблица затрат по виду транспорта."""
    result = df.groupby("Вид_транспорта").agg(
        Число_рейсов=("ID_рейса", "count"),
        Общая_стоимость_тенге=("Стоимость_тенге", "sum"),
        Средняя_стоимость_за_ткм=("Стоимость_за_ткм", "mean"),
    ).sort_values("Общая_стоимость_тенге", ascending=False)
    return result.round(2)


def costs_by_cargo_type(df: pd.DataFrame) -> pd.DataFrame:
    """Сводная таблица затрат по типу груза."""
    result = df.groupby("Тип_груза").agg(
        Число_рейсов=("ID_рейса", "count"),
        Общая_стоимость_тенге=("Стоимость_тенге", "sum"),
        Средняя_стоимость_за_ткм=("Стоимость_за_ткм", "mean"),
    ).sort_values("Общая_стоимость_тенге", ascending=False)
    return result.round(2)


def costs_by_month(df: pd.DataFrame) -> pd.DataFrame:
    """Динамика затрат по месяцам."""
    tmp = df.copy()
    tmp["Месяц"] = tmp["Дата"].dt.to_period("M").astype(str)
    result = tmp.groupby("Месяц").agg(
        Число_рейсов=("ID_рейса", "count"),
        Общая_стоимость_тенге=("Стоимость_тенге", "sum"),
    )
    return result.round(2)


# ------------------------------------------------------------------
# Аномалии тарифов (Неделя 12 плана, но пригодится уже сейчас)
# ------------------------------------------------------------------

def find_overpriced_trips(df: pd.DataFrame, threshold_pct: float = 15.0) -> pd.DataFrame:
    """
    Возвращает рейсы, тариф которых превышает среднерыночный
    более чем на threshold_pct % (по умолчанию 15%, как в плане).
    """
    overpriced = df[df["Отклонение_от_среднего_%"] > threshold_pct].copy()
    overpriced = overpriced.sort_values("Отклонение_от_среднего_%", ascending=False)

    cols = [
        "ID_рейса", "Дата", "Перевозчик", "Регион_отправления", "Регион_назначения",
        "Стоимость_за_ткм", "Отклонение_от_среднего_%", "Стоимость_тенге",
    ]
    overpriced = overpriced[cols]
    numeric_cols = ["Стоимость_за_ткм", "Отклонение_от_среднего_%", "Стоимость_тенге"]
    overpriced[numeric_cols] = overpriced[numeric_cols].round(2)
    return overpriced


def potential_savings(df: pd.DataFrame, threshold_pct: float = 15.0) -> float:
    """
    Оценивает потенциальную экономию (тенге), если бы все рейсы с завышенным
    тарифом (> threshold_pct% от среднего) стоили по среднерыночной ставке.
    """
    avg_rate = df["Стоимость_за_ткм"].mean()
    overpriced = df[df["Отклонение_от_среднего_%"] > threshold_pct]

    fair_cost = overpriced["Грузооборот_ткм"] * avg_rate
    savings = (overpriced["Стоимость_тенге"] - fair_cost).sum()
    return round(savings, 2)


# ------------------------------------------------------------------
# Текстовое резюме (пригодится для Недели 11)
# ------------------------------------------------------------------

def summary_report(df: pd.DataFrame) -> str:
    total_cost = df["Стоимость_тенге"].sum()
    total_ton_km = df["Грузооборот_ткм"].sum()
    avg_rate = df["Стоимость_за_ткм"].mean()
    n_trips = len(df)
    n_overpriced = (df["Отклонение_от_среднего_%"] > 15).sum()
    savings = potential_savings(df)

    top_carrier = costs_by_carrier(df).index[0]

    return (
        f"Всего рейсов: {n_trips}\n"
        f"Суммарные затраты: {total_cost:,.0f} тенге\n"
        f"Суммарный грузооборот: {total_ton_km:,.0f} т·км\n"
        f"Средний тариф: {avg_rate:,.2f} тенге/т·км\n"
        f"Перевозчик с наибольшими затратами: {top_carrier}\n"
        f"Рейсов с завышенным тарифом (>15%): {n_overpriced}\n"
        f"Потенциальная экономия: {savings:,.0f} тенге\n"
    )


if __name__ == "__main__":
    df = load_data()
    df = add_kpi_columns(df)

    print(summary_report(df))

    print("\n=== Затраты по перевозчикам ===")
    print(costs_by_carrier(df))

    print("\n=== Затраты по виду транспорта ===")
    print(costs_by_transport_type(df))

    print("\n=== Затраты по типу груза ===")
    print(costs_by_cargo_type(df))

    print("\n=== Топ-10 самых дорогих (относительно среднего) рейсов ===")
    print(find_overpriced_trips(df).head(10))
